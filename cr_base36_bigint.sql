DROP FUNCTION IF EXISTS BASE36_BIGINT;

DELIMITER $$

CREATE FUNCTION BASE36_BIGINT( BASE36 VARCHAR(100) )
RETURNS BIGINT
BEGIN
DECLARE $CODE INT;
DECLARE $NUM BIGINT;
SET $NUM=0;
WHILE BASE36 != '' DO
  SET $CODE = ASCII(BASE36)-48;
  SET BASE36=SUBSTRING(BASE36,2);
  IF $CODE > 9 THEN
    SET $CODE = $CODE-7;
  END IF;
  SET $NUM = $NUM*36+$CODE;
END WHILE;
RETURN $NUM;
END;$$

DELIMITER ;

-- TEST:
SELECT BASE36_BIGINT('1Z')=71,BASE36_BIGINT('1A')=46,BASE36_BIGINT('A')=10;


